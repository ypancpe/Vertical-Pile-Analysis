function row = ng_summary_row(inp, cap, st)
%NG_SUMMARY_ROW One flat struct row summarizing a case (for CSV / batch tables).
%
%   row = ng_summary_row(inp, cap, st)
%
%   Forces in kips (suffix _kips), unit resistances psf, settlement inches.
%   Used by ng_run_case (per-case summary CSV) and pile_calc_batch
%   (stacked batch CSV).

    row = struct( ...
        'case_name',       inp.case_name, ...
        'shape',           inp.pile.shape, ...
        'size_in',         inp.pile.size_in, ...
        'embedment_ft',    inp.pile.embedment_ft, ...
        'pile_type',       inp.pile.pile_type, ...
        'water_table_ft',  inp.pile.water_table_ft, ...
        'K_down',          inp.par.K_down, ...
        'K_up',            inp.par.K_up, ...
        'Kf',              inp.par.Kf, ...
        'PR',              inp.par.PR, ...
        'z_crit_ft',       cap.z_crit, ...
        'tip_desc',        cap.tip_desc, ...
        'qp_psf',          cap.qp, ...
        'Qside_down_kips', cap.Qside_down / 1000, ...
        'Qtip_kips',       cap.Qtip / 1000, ...
        'Qdown_ult_kips',  cap.Qdown_ult / 1000, ...
        'Qdown_allow_kips',cap.Qdown_allow / 1000, ...
        'Qside_up_kips',   cap.Qside_up / 1000, ...
        'W_kips',          cap.W / 1000, ...
        'Qup_ult_kips',    cap.Qup_ult / 1000, ...
        'Qup_allow_kips',  cap.Qup_allow / 1000, ...
        'Cp',              st.Cp, ...
        'xi',              st.xi, ...
        'Xs_in',           st.Xs, ...
        'Xpp_in',          st.Xpp, ...
        'Xps_in',          st.Xps, ...
        'Xmax_in',         st.Xmax, ...
        'Q_applied_kips',  st.Q_applied / 1000, ...
        'Q_over_Qult',     st.ratio, ...
        'Qwp_kips',        st.Qwp / 1000, ...
        'Qws_kips',        st.Qws / 1000, ...
        's_shaft_in',      st.s1, ...
        's_point_in',      st.s2, ...
        's_transfer_in',   st.s3, ...
        's_applied_in',    st.s_applied);
end
